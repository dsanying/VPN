test('匹配类型同步说明且不显示示例，切换类型保留草稿并重新校验，正则逗号原样保存', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('shadowvpn-lang', 'zh-CN'));
  const mock = await installDesktopMock(page);
  await page.goto('/#/rules');
  registerFirefoxPopupPositioningDiagnostic(page);
  await page.getByRole('button', { name: '新增', exact: true }).click();
  await page.getByRole('menuitem', { name: '匹配规则', exact: true }).click();
  const drawer = page.getByRole('dialog');
  const input = drawer.getByLabel('匹配值', { exact: true });
  const help = drawer.locator('.ant-form-item').filter({ has: page.getByRole('textbox', { name: /匹配值/ }) }).locator('.ant-form-item-tooltip');
  await expect(input).not.toHaveAttribute('placeholder');
  await expect(drawer.getByText(/匹配该域名及其子域名/)).toHaveCount(0);
  await help.hover();
  await expect(page.getByRole('tooltip')).toHaveText('匹配该域名及其子域名，不带 https:// 或路径。 每行一个值');
  await input.fill('example.com');
  await drawer.getByLabel('匹配类型', { exact: true }).click();
  await page.getByRole('option', { name: '目标端口', exact: true }).click();
  await expect(input).toHaveValue('example.com');
  await expect(input).not.toHaveAttribute('placeholder');
  await expect(drawer.getByText(/填写 1–65535/)).toHaveCount(0);
  await help.hover();
  await expect(page.getByRole('tooltip')).toHaveText('填写 1–65535 的端口，范围写成起始值-结束值。 每行一个值');
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer.getByText('格式不正确，请检查输入', { exact: true })).toBeVisible();
  await input.fill('443\n8000-8080');
  await expect(drawer.locator('.ant-form-item-explain-error')).toHaveCount(0);
  await drawer.getByLabel('匹配类型', { exact: true }).click();
  await page.getByRole('option', { name: '域名正则', exact: true }).click();
  await expect(input).toHaveValue('443\n8000-8080');
  await expect(input).not.toHaveAttribute('placeholder');
  await help.hover();
  await expect(page.getByRole('tooltip')).toHaveText('使用 RE2 正则表达式，不支持前后查找和反向引用。 每行一个值');
  await input.fill('(?=example)');
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer.getByText('格式不正确，请检查输入', { exact: true })).toBeVisible();
  await input.fill('^example{1,2}\\.com$\n^example\\.net$');
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer).not.toBeVisible();
  const saved = await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0]);
  expect(saved.type).toBe('domainRegex');
  expect(saved.values).toEqual(['^example{1,2}\\.com$', '^example\\.net$']);
  await mock.expectNoUnexpectedRequests();
});

test('匹配值空白只报必填，非空非法值只报格式，修正后错误消失', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('shadowvpn-lang', 'zh-CN'));
  const mock = await installDesktopMock(page);
  await page.goto('/#/rules');
  await page.getByRole('button', { name: '新增', exact: true }).click();
  await page.getByRole('menuitem', { name: '匹配规则', exact: true }).click();
  const drawer = page.getByRole('dialog');
  const input = drawer.getByLabel('匹配值', { exact: true });
  await expect(drawer.locator('.ant-form-item-explain-error')).toHaveCount(0);
  await drawer.getByLabel('备注', { exact: true }).fill('Example rule');
  for (const value of ['', '  \n  ']) {
    await input.fill(value);
    await drawer.getByRole('button', { name: /保存$/ }).click();
    await expect(drawer.locator('.ant-form-item-explain-error')).toHaveCount(1);
    await expect(drawer.getByText('请输入匹配值', { exact: true })).toBeVisible();
    await expect(drawer.getByText('格式不正确，请检查输入', { exact: true })).toHaveCount(0);
  }
  await input.fill('https://example.com');
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer.locator('.ant-form-item-explain-error')).toHaveCount(1);
  await expect(drawer.getByText('格式不正确，请检查输入', { exact: true })).toBeVisible();
  await expect(drawer.getByText('请输入匹配值', { exact: true })).toHaveCount(0);
  await input.fill('example.com\nexample.net');
  await expect(drawer.locator('.ant-form-item-explain-error')).toHaveCount(0);
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer).not.toBeVisible();
  expect(await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0].values)).toEqual(['example.com', 'example.net']);
  await mock.expectNoUnexpectedRequests();
});

test('单一条件入口，多条件才显示组合方式，保存和删除条件保持同一逻辑', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('shadowvpn-lang', 'zh-CN'));
  const mock = await installDesktopMock(page);
  await page.setViewportSize({ width: 960, height: 600 });
  await page.goto('/#/rules');
  await page.getByRole('button', { name: '新增', exact: true }).click();
  await page.getByRole('menuitem', { name: '匹配规则', exact: true }).click();
  const drawer = page.getByRole('dialog');
  await expect(drawer.locator('.monaco-editor')).toHaveCount(0);
  await expect(drawer.getByLabel('匹配类型', { exact: true })).toHaveCount(1);
  await expect(drawer.getByLabel('组合方式', { exact: true })).toHaveCount(0);
  await drawer.getByLabel('匹配值', { exact: true }).fill('example.com\nexample.net');
  await drawer.getByRole('button', { name: '新增', exact: true }).click();
  const combine = drawer.getByLabel('组合方式', { exact: true });
  await expect(combine.locator('..')).toContainText('任一满足');
  await combine.click(); await page.getByRole('option', { name: '全部满足', exact: true }).click();
  await drawer.getByLabel('匹配类型', { exact: true }).nth(1).click();
  await page.getByRole('option', { name: '目标端口', exact: true }).click();
  await drawer.getByLabel('匹配值', { exact: true }).nth(1).fill('443');
  await drawer.getByLabel('去向', { exact: true }).click();
  await page.getByRole('option', { name: '直连', exact: true }).click();
  await expect(drawer.getByLabel('指定节点', { exact: true })).toHaveCount(0);
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer).not.toBeVisible();
  const saved = await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0]);
  expect(saved.conditions).toEqual([{ type: 'domainSuffix', values: ['example.com', 'example.net'] }, { type: 'port', values: ['443'] }]);
  expect(saved.combineMode).toBe('and');
  await page.locator('tbody tr[data-row-key]').first().getByRole('button', { name: '编辑', exact: true }).click();
  await expect(drawer.getByLabel('匹配值', { exact: true })).toHaveCount(2);
  await drawer.getByRole('button', { name: '删除', exact: true }).nth(1).click();
  await page.getByRole('button', { name: /确定$/, exact: true }).click();
  await expect(drawer.getByLabel('组合方式', { exact: true })).toHaveCount(0);
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer).not.toBeVisible();
  const single = await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0]);
  expect(single.values).toEqual(['example.com', 'example.net']);
  expect(single.conditions).toBeUndefined(); expect(single.combineMode).toBeUndefined();
  await mock.expectNoUnexpectedRequests();
});

test('编辑取实际条件，保留未显示字段，空白及无效值不保存', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('shadowvpn-lang', 'zh-CN'));
  const mock = await installDesktopMock(page);
  await page.goto('/#/rules'); await expect(page.getByRole('table')).toBeVisible();
  await page.evaluate(async () => {
    const config = structuredClone((window as any).desktopTest.getConfig());
    config.customRules = [{ id: 'test-rule', type: 'port', values: ['80'], conditions: [{ type: 'domainSuffix', values: ['example.com'] }, { type: 'port', values: ['443'] }], combineMode: 'and', enabled: false, action: 'proxy', bypassFakeIP: true, remarks: '保留备注', extension: { keep: true } }];
    await (window as any).electron.ipcRenderer.invoke('config:save', { config });
  });
  await page.locator('tbody tr[data-row-key]').first().getByRole('button', { name: '编辑', exact: true }).click();
  const drawer = page.getByRole('dialog');
  await expect(drawer.getByLabel('匹配值', { exact: true }).first()).toHaveValue('example.com');
  await drawer.getByLabel('匹配值', { exact: true }).nth(1).fill('99999');
  await drawer.getByRole('button', { name: /保存$/ }).click();
  await expect(drawer.getByText('格式不正确，请检查输入', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0].values)).toEqual(['80']);
  await drawer.getByLabel('匹配值', { exact: true }).nth(1).fill('  ');
  await drawer.getByRole('button', { name: /保存$/ }).click(); await expect(drawer).toBeVisible();
  await drawer.getByLabel('匹配值', { exact: true }).nth(1).fill('8443');
  await drawer.getByRole('button', { name: /保存$/ }).click(); await expect(drawer).not.toBeVisible();
  const saved = await page.evaluate(() => (window as any).desktopTest.getConfig().customRules[0]);
  expect(saved.type).toBe('domainSuffix'); expect(saved.values).toEqual(['example.com']);
  expect(saved.conditions[1].values).toEqual(['8443']);
  expect(saved.extension).toEqual({ keep: true }); expect(saved.bypassFakeIP).toBe(true);
  expect(saved.enabled).toBe(false); expect(saved.combineMode).toBe('and'); expect(saved.remarks).toBe('保留备注');
  await mock.expectNoUnexpectedRequests();
});
